import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const DIST = join(here, '..', 'app', 'dist');
const ASSETS = join(DIST, 'assets');
const GZIP_FLAG_LIMIT = 200 * 1024;

const ROUTES = [
  ['/today', 'TodayPage'],
  ['/plan', 'PlanPage'],
  ['/stats', 'StatsPage'],
  ['/settings', 'SettingsPage'],
  ['/workout/:id', 'WorkoutPage'],
  ['/run/:id', 'GuidedRunPage'],
  ['/race-day', 'RaceDayPage'],
  ['/benchmark', 'BenchmarkPage'],
  ['/leaderboard', 'LeaderboardPage'],
  ['/friends', 'FriendsPage'],
];

const HEAVY_LIBS = [
  { name: 'supabase-js', marker: 'createClient' },
  { name: 'i18next', marker: 'saveMissing' },
  { name: 'motion', marker: 'framerAppearId' },
  { name: 'capacitor', marker: 'Capacitor' },
];

const FONT_SUBSETS = ['inter-latin-wght-normal', 'inter-latin-ext-wght-normal'];
const UNUSED_FONT_SUBSETS = ['cyrillic', 'greek', 'vietnamese'];

function formatSize(bytes) {
  return (bytes / 1024).toFixed(1);
}

function readAsset(name) {
  return readFileSync(join(ASSETS, name), 'utf8');
}

function staticImports(text) {
  return [...text.matchAll(/from"\.\/([^"]+)"/g)].map((match) => match[1]);
}

function startupClosure(entry) {
  const files = new Set([entry]);
  let frontier = [entry];
  while (frontier.length > 0) {
    const next = [];
    for (const file of frontier) {
      for (const imported of staticImports(readAsset(file))) {
        if (!files.has(imported)) {
          files.add(imported);
          next.push(imported);
        }
      }
    }
    frontier = next;
  }
  return files;
}

function precacheEntries() {
  const sw = readFileSync(join(DIST, 'sw.js'), 'utf8');
  const urls = [...sw.matchAll(/\{url:"([^"]+)"[^}]*\}/g)].map((match) => match[1]);
  return { urls: [...new Set(urls)], duplicates: urls.filter((url, index) => urls.indexOf(url) !== index) };
}

const assetNames = readdirSync(ASSETS).filter((name) => /\.(js|css)$/.test(name));
const entryName = assetNames.find((name) => /^index-.*\.js$/.test(name));
const closure = startupClosure(entryName);

const rows = assetNames
  .map((name) => {
    const raw = statSync(join(ASSETS, name)).size;
    const gzip = gzipSync(readFileSync(join(ASSETS, name))).length;
    const text = name.endsWith('.js') ? readAsset(name) : '';
    const libs = HEAVY_LIBS.filter((lib) => text.includes(lib.marker)).map((lib) => lib.name);
    return {
      name,
      raw,
      gzip,
      kind: name === entryName ? 'entry' : name.endsWith('.css') ? 'css' : 'chunk',
      inStartup: closure.has(name),
      libs,
    };
  })
  .sort((a, b) => b.raw - a.raw);

const failures = [];

console.log('## Bundle report');
console.log('');
console.log(
  'Generated by `node scripts/bundle-report.mjs` from `app/dist` (Vite production build). Sizes are 1024-based.',
);
console.log('');
console.log('| File | Raw (kB) | Gzip (kB) | Kind | In startup | Heavy libs |');
console.log('| ---- | -------- | --------- | ---- | ---------- | ---------- |');
for (const row of rows) {
  const gzipFlag = row.gzip > GZIP_FLAG_LIMIT ? ' >200 kB gzip' : '';
  console.log(
    `| \`${row.name}\` | ${formatSize(row.raw)} | ${formatSize(row.gzip)}${gzipFlag} | ${row.kind} | ${row.inStartup ? 'yes' : 'no'} | ${row.libs.join(', ') || '-'} |`,
  );
}
console.log('');

if (rows.some((row) => row.gzip > GZIP_FLAG_LIMIT)) {
  failures.push(
    `chunk over 200 kB gzip: ${rows
      .filter((row) => row.gzip > GZIP_FLAG_LIMIT)
      .map((row) => row.name)
      .join(', ')}`,
  );
} else {
  console.log(`OK: no chunk exceeds 200 kB gzip (largest: ${rows[0].name}, ${formatSize(rows[0].gzip)} kB gzip)`);
}

let startupRaw = 0;
let startupGzip = 0;
for (const name of closure) {
  const file = join(ASSETS, name);
  startupRaw += statSync(file).size;
  startupGzip += gzipSync(readFileSync(file)).length;
}
console.log(
  `Startup closure: entry plus ${closure.size - 1} static chunks, ${formatSize(startupRaw)} kB raw / ${formatSize(startupGzip)} kB gzip`,
);
console.log('');

console.log('## Lazy route chunks');
console.log('');
console.log('| Route | Page chunk | Separate file | Not in entry closure |');
console.log('| ----- | ---------- | ------------- | -------------------- |');
for (const [route, prefix] of ROUTES) {
  const name = assetNames.find((asset) => new RegExp(`^${prefix}-.*\\.js$`).test(asset));
  const separate = Boolean(name);
  const lazy = separate && !closure.has(name);
  if (!lazy) failures.push(`${route} is not a separate lazy chunk (${name ?? 'missing'})`);
  console.log(
    `| \`${route}\` | ${name ? `\`${name}\`` : 'missing'} | ${separate ? 'yes' : 'no'} | ${lazy ? 'yes' : 'no'} |`,
  );
}
console.log('');

console.log('## Heavy library split');
console.log('');
console.log('| Library | Marker | Chunks | Verdict |');
console.log('| ------- | ------ | ------ | ------- |');
for (const lib of HEAVY_LIBS) {
  const chunks = rows.filter((row) => row.libs.includes(lib.name));
  const entryHit = chunks.some((row) => row.name === entryName);
  const verdict = chunks.length === 1 && !entryHit ? 'OK' : entryHit ? 'in entry' : 'duplicated';
  if (verdict !== 'OK') failures.push(`${lib.name} is ${verdict} (${chunks.map((row) => row.name).join(', ')})`);
  console.log(`| ${lib.name} | \`${lib.marker}\` | ${chunks.map((row) => row.name).join(', ') || '-'} | ${verdict} |`);
}
console.log('');

const precacheData = precacheEntries();
const precache = precacheData.urls;
if (precacheData.duplicates.length > 0) {
  failures.push(`duplicate precache entries: ${[...new Set(precacheData.duplicates)].join(', ')}`);
}
let precacheRaw = 0;
for (const url of precache) {
  const file = join(DIST, url);
  try {
    precacheRaw += statSync(file).size;
  } catch {
    failures.push(`precached url missing from dist: ${url}`);
  }
}
const precachedFonts = precache.filter((url) => url.endsWith('.woff2'));
const missingSubsets = FONT_SUBSETS.filter((subset) => !precachedFonts.some((url) => url.includes(subset)));
const unusedPrecached = precachedFonts.filter((url) => UNUSED_FONT_SUBSETS.some((subset) => url.includes(subset)));
if (missingSubsets.length > 0) failures.push(`missing font subsets in precache: ${missingSubsets.join(', ')}`);
if (unusedPrecached.length > 0) failures.push(`unused font subsets in precache: ${unusedPrecached.join(', ')}`);
if (!precache.includes('index.html')) failures.push('index.html is not precached');

console.log('## Service worker precache');
console.log('');
console.log(
  `Entries: ${precache.length}. Total: ${formatSize(precacheRaw)} kB. Navigation fallback: ${/createHandlerBoundToURL\("\/index\.html"\)/.test(readFileSync(join(DIST, 'sw.js'), 'utf8')) ? '/index.html precached' : 'missing'}.`,
);
console.log(`Fonts precached: ${precachedFonts.map((url) => url.split('/').pop()).join(', ') || '-'}`);
console.log('');

console.log('## Checks');
console.log('');
for (const failure of failures) console.log(`- FAIL: ${failure}`);
console.log(
  `- ${rows.length} assets measured, ${closure.size} in startup closure, ${precache.length} precached entries`,
);
console.log(`Result: ${failures.length === 0 ? 'PASS' : 'FAIL'} (${failures.length} failures)`);

process.exitCode = failures.length === 0 ? 0 : 1;
